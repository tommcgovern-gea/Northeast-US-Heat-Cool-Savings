export function PasswordToggle({
  show,
  onToggle,
  labelHide = "Hide password",
  labelShow = "Show password",
}: {
  show: boolean;
  onToggle: () => void;
  labelHide?: string;
  labelShow?: string;
}) {
  return (
    <button
      type="button"
      onClick={onToggle}
      className="absolute inset-y-0 right-0 flex w-10 items-center justify-center text-gray-500 hover:text-gray-700"
      aria-label={show ? labelHide : labelShow}
    >
      {show ? <EyeOffIcon /> : <EyeIcon />}
    </button>
  );
}
